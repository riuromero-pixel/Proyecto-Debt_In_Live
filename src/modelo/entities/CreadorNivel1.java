package src.modelo.entities;

import src.modelo.map.Mapa;
import src.modelo.map.Pared;

public class CreadorNivel1 extends CreadorNivel {

    @Override
    public int getNivel() {
        return 1;
    }

    @Override
    public int getSpawnX() { return 4; }
    @Override
    public int getSpawnY() { return 4; }

    @Override
    public String getMensajeDerrota() {
        return "¡PERDISTE! Te quedaste sin plata. Chau play 5:(";
    }

    @Override
    public String getMensajeVictoria() {
        return "¡Bien ahi! Ganaste el juego! Lograste sobrevivir a las deudas de la vida.";
    }

    @Override
    protected Personaje crearPersonaje(int x, int y, Mapa mapa) {
        return new Estudiante(x, y, mapa);
    }

    @Override
    protected void cargarPlantilla(Mapa mapa) {
        String[] plantilla = {
            "########################################",
            "#......................................#",
            "#.......+....................+.........#",
            "#................+.....................#",
            "#......................................#",
            "###############..........###############",
            "#......................................#",
            "#........####................####......#",
            "#......................................#",
            "#........####................####......#",
            "#......................................#",
            "#......................................#",
            "#......+...............................#",
            "#......................................#",
            "#......+...............................#",
            "###############..........###############",
            "#............+.........................#",
            "#........####................####......#",
            "#......................................#",
            "#........####................####......#",
            "#......................+...............#",
            "#........+.............................#",
            "#..####....####..........####....####..#",
            "#......................................#",
            "#..####....####..........####....####..#",
            "#......................................#",
            "#......................+...............#",
            "#........+.............................#",
            "#......................+...............#",
            "#........+.............................#",
            "#.........+++++++......................#",
            "#......................................#",
            "#..####....####..........####....####..#",
            "#......................................#",
            "#..####....####..........####....####..#",
            "#......................................#",
            "#......................................#",
            "#..............++++....................#",
            "#......................................#",
            "########################################"
        };
        for (int y = 0; y < plantilla.length && y < mapa.getAlto(); y++) {
            for (int x = 0; x < plantilla[y].length() && x < mapa.getAncho(); x++) {
                char caracter = plantilla[y].charAt(x);
                if (caracter == '#') {
                    mapa.setContenido(x, y, new Pared(0));
                } else if (caracter == '+') {
                    mapa.setContenido(x, y, new Pared());
                }
            }
        }
    }
}